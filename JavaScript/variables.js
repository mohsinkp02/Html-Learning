//! variables - it is like a container which is used to store some data in it.
//! To declare a variable in JS, we use var, let and const keywords.
//! To declare a variable in JS, we no need to mention any datatype.
//! Once a variable is declared in javascript , it can store any type of data in it.

//! var keyword
var a;              //?declaration is possible
a=10;               //?initialization is possible
console.log(a);
var a;              //?redeclaration is possible
a=100;              //?reinitialization is possible
console.log(a);

//! let keyword
let b;              //declaration is possible
b=20;               //initialization is possible
console.log(b);

// let b;           //redeclaration is not possible
